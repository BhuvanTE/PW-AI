//for loop excute specified number of times
for (let i = 0; i < 5; i++) {
    console.log("The value of i is: " + i);
}

//print numbers from 1 to 10
for (let i = 1; i <= 10; i++) {
    console.log(i);
}

//print  numbers from 10 to 1
for (let i = 10; i >= 1; i--) {
    console.log(i);
}

//print even numbers from 1 to 20
for (let i = 1; i <= 20; i++) {
    if (i % 2 == 0) {
        console.log(i);
    }
}